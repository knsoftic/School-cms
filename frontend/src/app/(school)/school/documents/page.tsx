'use client';

/**
 * Documents — SRS §20.5, §33's "Documents", checklist row 4.4.
 *
 * ## The one screen with no module gate, and the reason is worth knowing
 *
 * Every other module router mounts `requireModule(...)`. This one mounts
 * `requireActiveSubscription()` instead, because §20.5's seven document types span **four**
 * subscribable modules — `DOCUMENT_TYPE_MODULE` maps them onto `id_cards`, `certificates`, `fees`
 * and `exams`. There is no single key to gate on, so the module check happens per document type
 * inside the service.
 *
 * That has a visible consequence: this screen can load and list documents while a *particular* type
 * is still unavailable. A refusal on generating one is not a refusal of the screen.
 *
 * ## `file_path` never arrives, and that is the design
 *
 * `documents.service.js:128-132` deletes it and returns `has_file` instead. The bytes come from
 * `GET /documents/{id}?format=pdf`, which re-checks the tenant on the way out. A column showing the
 * path would be showing a value the API deliberately withholds — and one that was null anyway.
 *
 * ## The teacher and the exam come from the documents pick-lists — owner decision D34
 *
 * FR-DOC-001 names the Accountant and the Receptionist as actors, and neither holds `teachers.view`
 * or `exams.view` — so a Teacher ID Card and a Result Card, the two documents that name a teacher and
 * an exam, could not be generated by exactly the people the requirement names: the dialog read
 * `GET /teachers` and `GET /exams` and got nothing. D34 answered with two small lists under the key
 * that opens this dialog, `documents.generate`: `GET /documents/pickers/teachers` and
 * `/documents/pickers/exams`. The dialog reads them for **every** caller rather than only for one
 * without the view keys: they answer the same question on the key the dialog already requires, and
 * they sit on this router, which checks the subscription's state and not the Teachers or Exams module
 * — so one code path serves every actor, and a grant edited later cannot empty the list. Both take
 * `q` and return at most fifty, with no total; the hints say when a list may have been cut there.
 */

